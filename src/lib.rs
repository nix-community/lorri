/// Start a tokio local thread runtime which allows us to use `tokio::task::spawn_local` everywhere.
pub fn lorri_runtime_block_on<O>(async_block: impl Future<Output = O> + Sized) -> O {
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .expect("unable to start lorri tokio runtime");
    tokio::task::LocalSet::new().block_on(&runtime, async_block)
}

